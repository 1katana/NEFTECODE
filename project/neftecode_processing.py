def artifact_root(base: Path | str | None = None) -> Path:
  # Абсолютный корень артефактов
  if base is None:
    env = os.environ.get("NEFTECODE_ARTIFACTS")
    base = Path(env) if env else Path.cwd() / "artifacts"
  root = Path(base).expanduser().resolve()
  root.mkdir(parents=True, exist_ok=True)
  log.info("Артефакты будут сохранены в: %s", root)
  return root

def _json_safe(df: pd.DataFrame) -> list[dict]:
  # DataFrame -> список словарей, пригодных для json.dumps
  d = df.copy()
  for c in d.columns:
    if pd.api.types.is_datetime64_any_dtype(d[c]):
      d[c] = d[c].dt.strftime("%Y-%m-%d %H:%M:%S")
  return json.loads(d.to_json(orient="records", date_format="iso"))

def save_df(df: pd.DataFrame, name: str, root: Path, fmt: SaveFormat = "both",
            also_parquet: bool = False) -> Path:
  # Сохраняет DataFrame в csv/json/parquet
  root.mkdir(parents=True, exist_ok=True)
  written: list[Path] = []

  if fmt in ("csv", "both"):
    csv_path = root/f"{name}.csv"
    df.to_csv(csv_path, index=False, date_format="%Y-%m-%d %H:%M:%S")
    written.append(csv_path)

  if fmt in ("json", "both"):
    json_path = root/f"{name}.json"
    json_path.write_text(json.dumps(_json_safe(df), ensure_ascii=False,
                                    indent=2), encoding="utf-8")
    written.append(json_path)

  if also_parquet:
    try:
      parquet_path = root/f"{name}.parquet"
      df.to_parquet(parquet_path, index=False)
      written.append(parquet_path)
    except Exception as e:
      log.warning("Parquet недоступен (%s); пропускаю.", e)

  main = written[0] if written else (root / f"{name}.csv")
  log.info("Сохранено: %s (%s)", [str(p.name) for p in written], df.shape)
  return main

# Срезы под агентов
QUALITY_INDICATORS = ["sulfur", "d15", "density", "cloud", "flash", "t50",
                      "t90", "t95", "cfpp", "pour", "viscosity", "cetane",
                      "ibp", "ebp", "i250", "i350"]

def build_quality_view(final: pd.DataFrame) -> pd.DataFrame:
  # Для агента качества: timestamp + *_value/*_age_min/*_src/*_flag_*,
  # у которых indicator похож на показатель качества
  cols = ["timestamp"]
  for c in final.columns:
    c_low = c.lower()
    if c_low == "timestamp":
      continue
    if any(k in c_low for k in QUALITY_INDICATORS):
      cols.append(c)
  cols = [c for c in cols if c in final.columns]
  return final[cols].copy()

def build_reliability_view(final: pd.DataFrame) -> pd.DataFrame:
  # Для агента надежности: режимные теги avt_*/hyd_* + все *_flag_*
  keep = ["timestamp"]
  for c in final.columns:
    c_low = c.lower()
    if c_low == "timestamp":
      continue
    if c_low.endswith(("_age_min", "_src")):
      continue
    if c_low.endswith(("_flag_stale", "_flag_missing", "_flag_outlier")):
      keep.append(c)
      continue
    if re.match(r"^(avt|hyd)_[a-z]\d+$", c_low):
      keep.append(c)
  keep = [c for c in keep if c in final.columns]
  return final[keep].copy()

def build_orchestrator_view(final: pd.DataFrame) -> pd.DataFrame:
  # Для оркестратора: timestamp + ключевые технологические теги + все *_value
  preferred = [
      # АВТ
      "avt_t1", "avt_p2", "avt_t6", "avt_t20", "avt_p21", "avt_t33",
      "avt_t48", "avt_p44", "avt_p50", "avt_f7", "avt_f8", "avt_f9",
      "avt_f30", "avt_f32", "avt_f34", "avt_f45", "avt_f16",
      # 24-2000
      "hyd_t5", "hyd_p8", "hyd_f9", "hyd_t11", "hyd_t12", "hyd_t18",
      "hyd_f22", "hyd_t23", "hyd_p24", "hyd_f26",
  ]
  preferred = [c.lower() for c in preferred]
  cols = ["timestamp"] + [c for c in preferred if c in final.columns]
  cols += [c for c in final.columns if c.endswith("_value")]
  cols = list(dict.fromkeys(cols))
  return final[cols].copy()

def export_agent_views(final: pd.DataFrame, root: Path,
                       fmt: SaveFormat = "both") -> dict[str, Path]:
  # Сохраняет три среза + сам final; возвращает {name: path}
  out = {}
  out["final"] = save_df(final, "final", root, fmt=fmt)
  out["view_quality"] = save_df(build_quality_view(final), "view_quality",
                                root, fmt=fmt)
  out["view_reliability"] = save_df(build_reliability_view(final),
                                    "view_reliability", root, fmt=fmt)
  out["view_orchestrator"] = save_df(build_orchestrator_view(final),
                                      "view_orchestrator", root, fmt=fmt)
  return out


def run_processing(
    paths: Paths,
    artifact_dir: Path | str | None = None,
    *,
    fmt: SaveFormat = "csv",
    include_report: bool = False,
) -> tuple[dict, dict[str, Path]]:
  """Запускает общий пайплайн и экспортирует контрактные срезы.

  Эту функцию используют и CLI, и HTTP-загрузка: потребитель всегда получает
  ``final`` и ``view_orchestrator`` из одной и той же предобработки.
  """
  data = build_preprocessed_dataset(paths)
  root = artifact_root(artifact_dir)
  saved: dict[str, Path] = {}
  for name in ("telemetry", "lims", "pak", "vak", "kip", "quality_merged", "final"):
    df = data.get(name)
    if isinstance(df, pd.DataFrame) and not df.empty:
      saved[name] = save_df(df, name, root, fmt=fmt)
  for split_name, df in data["splits"].items():
    if isinstance(df, pd.DataFrame) and not df.empty:
      saved[f"split_{split_name}"] = save_df(df, f"split_{split_name}", root, fmt=fmt)
  saved.update(export_agent_views(data["final"], root, fmt=fmt))

  if include_report:
    plots_dir = root / "plots"
    pngs: list[Path] = []
    try:
      pngs += plot_quality_trends(data["final"], plots_dir)
      pngs.append(plot_missing_map(data["final"], plots_dir))
    except Exception as error:
      log.warning("Не удалось построить графики: %s", error)
    write_html_report(
        root,
        {key: value.shape for key, value in data.items() if isinstance(value, pd.DataFrame)},
        pngs,
    )
  return data, saved

# Графики и HTML-отчет
def plot_quality_trends(final: pd.DataFrame, out_dir: Path) -> list[Path]:
  # По каждому *_value: значение + возраст анализа
  import matplotlib
  matplotlib.use("Agg")
  import matplotlib.pyplot as plt

  out_dir.mkdir(parents=True, exist_ok=True)
  saved: list[Path] = []
  for col in [c for c in final.columns if c.endswith("_value")]:
    base = col[:-len("_value")]
    age_col = f"{base}_age_min"
    fig, ax1 = plt.subplots(figsize=(12, 3.5))
    ax1.plot(final["timestamp"], final[col], color="C0", lw=1)
    ax1.set_ylabel(col, color="C0")
    ax1.tick_params(axis="y", labelcolor="C0")
    if age_col in final.columns:
      ax2 = ax1.twinx()
      ax2.plot(final["timestamp"], final[age_col], color="C1", lw=1, alpha=0.5)
      ax2.set_ylabel("age, min", color="C1")
      ax2.tick_params(axis="y", labelcolor="C1")
    ax1.set_title(f"{col} и возраст анализа")
    fig.tight_layout()
    p = out_dir / f"trend_{base}.png"
    fig.savefig(p, dpi=110)
    plt.close(fig)
    saved.append(p)
  log.info("Графиков построено: %d", len(saved))
  return saved

def plot_missing_map(final: pd.DataFrame, out_dir: Path) -> Path:
  # Карта пропусков: heatmap долей NaN по 6-часовым бакетам
  import matplotlib
  matplotlib.use("Agg")
  import matplotlib.pyplot as plt

  out_dir.mkdir(parents=True, exist_ok=True)
  cols = [c for c in final.columns if not c.endswith(("_age_min", "_src",
                                                      "_flag_stale",
                                                      "_flag_missing",
                                                      "_flag_outlier"))]
  sub = final.set_index("timestamp")[cols].isna().resample("6h").mean()
  fig, ax = plt.subplots(figsize=(14, min(0.25*len(cols)+2, 20)))
  im = ax.imshow(sub.T.values, aspect="auto", cmap="magma", vmin=0, vmax=1)
  ax.set_yticks(range(len(cols)))
  ax.set_yticklabels(cols, fontsize=6)
  step = max(1, len(sub)//10)
  ax.set_xticks(range(0, len(sub), step))
  ax.set_xticklabels([t.strftime("%Y-%m-%d") for t in sub.index[::step]],
                     rotation=45, ha="right", fontsize=7)
  ax.set_title("Доля NaN по 6-часовым бакетам")
  fig.colorbar(im, ax=ax, shrink=0.6)
  fig.tight_layout()
  p = out_dir/"missing_map.png"
  fig.savefig(p, dpi=110)
  plt.close(fig)
  log.info("Карта пропусков: %s", p)
  return p

def write_html_report(root: Path, summary: dict, pngs: list[Path]) -> Path:
  # Сводный HTML с метриками и графиками
  html = ["<html><head><meta charset='utf-8'>",
          "<title>Предобработка — отчёт</title>",
          "<style>body{font-family:sans-serif;max-width:1100px;margin:20px auto}",
          "img{max-width:100%;border:1px solid #ccc;margin:8px 0}",
          "table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:4px 8px}",
          "</style></head><body>",
          "<h1>Предобработка данных — отчёт</h1>",
          "<h2>Сводка</h2><table>",
          "<tr><th>артефакт</th><th>shape</th></tr>"]
  for k, v in summary.items():
    html.append(f"<tr><td>{k}</td><td>{v}</td></tr>")
  html.append("</table><h2>Графики</h2>")
  for p in pngs:
    html.append(f"<h3>{p.name}</h3><img src='plots/{p.name}'>")
  html.append("</body></html>")
  out = root/"report.html"
  out.write_text("\n".join(html), encoding="utf-8")
  log.info("HTML-отчёт: %s", out)
  return out

